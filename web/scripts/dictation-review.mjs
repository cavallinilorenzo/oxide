import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { openReview } from "./ui-review.mjs";

const output = "docs/ui-review/dictation";
await mkdir(output, { recursive: true });
const { browser, page, errors } = await openReview("chromium", "empty", true);
try {
  await page.getByRole("button", { name: "New Thread", exact: true }).first().click();
  const input = page.getByRole("textbox", { name: "Message to agent" });
  await input.focus();
  await page.keyboard.press("Control+Shift+R");
  await page.getByRole("status").filter({ hasText: "Listening" }).waitFor();
  await page.screenshot({ path: `${output}/recording.png` });
  await page.keyboard.press("Control+Shift+R");
  await page.waitForFunction(() => document.querySelector('[aria-label="Message to agent"]').textContent.includes("Test di dettatura locale"));
  assert.equal(await page.evaluate(() => window.__OXIDE_REVIEW_COMMAND_COUNTS__.send_prompt ?? 0), 0);
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  const section = page.locator('[aria-labelledby="settings-dictation"]');
  await section.scrollIntoViewIfNeeded();
  await section.getByText(/RAM 6.30 GiB/).waitFor();
  await section.getByRole("button", { name: "Download large-v3-turbo", exact: true }).waitFor();
  await section.getByText("Advanced GPU backend and adapter", { exact: true }).click();
  await section.getByRole("combobox", { name: "GPU backend and adapter" }).focus();
  assert.equal(await section.getByRole("combobox", { name: "GPU backend and adapter" }).evaluate(el => el === document.activeElement), true);
  await section.getByText("Advanced GPU backend and adapter", { exact: true }).click();
  await page.screenshot({ path: `${output}/settings.png` });
  await page.setViewportSize({ width: 1064, height: 700 });
  await section.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/settings-1064.png` });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 600, height: 800 });
  await section.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/settings-600.png` });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const device = section.getByRole("button", { name: "Dictation device: CPU", exact: true });
  await device.focus(); await page.keyboard.press("ArrowDown");
  await page.getByRole("listbox", { name: "Dictation device" }).waitFor();
  await page.keyboard.press("Home"); await page.keyboard.press("Enter");
  await section.getByRole("button", { name: "Dictation device: Auto", exact: true }).waitFor();
  await section.getByRole("button", { name: "Dictation device: Auto", exact: true }).click();
  await page.keyboard.press("Escape");
  assert.equal(await section.getByRole("button", { name: "Dictation device: Auto", exact: true }).evaluate(el => el === document.activeElement), true);
  await section.getByRole("article", { name: "Model small", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/models-600.png` });
  await section.getByRole("button", { name: "Check performance", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${output}/performance-600.png` });
  assert.deepEqual(errors, []);
  console.log("Dictation shortcut, insertion without submit, Settings and minimum window width verified.");
} finally { await browser.close(); }
